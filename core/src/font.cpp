constexpr std::array<std::array<uint8_t, kHeight>, 95> build() {
  std::array<std::array<uint8_t, kHeight>, 95> out{};
  for (int g = 0; g < 95; ++g) {
    const char* s = kGlyphs[g];
    for (int row = 0; row < kHeight; ++row) {
      uint8_t bits = 0;
      for (int x = 0; x < 5; ++x) bits = static_cast<uint8_t>((bits << 1) | (s[row * 6 + x] == '#'));
      out[g][row] = bits;
    }
  }
  return out;
}

constexpr auto kBits = build();

